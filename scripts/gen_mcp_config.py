#!/usr/bin/env python3
"""Generate a project-scoped Harness MCP config for the CTF-Solver Manager.

The Beta does not edit global Harness profiles. It registers the Manager through the
project-scoped Workspace MCP Bridge: a ``.dsh/mcp.servers.yml`` file under the workspace
that will be opened in DeepSeek Harness.

This helper writes that file with no hardcoded machine paths:

* the workspace comes from ``--workspace``;
* the interpreter comes from ``--python`` (default: the interpreter running this script);
* ``--lead-sessions-root`` defaults to ``$DSH_HOME/sessions`` or ``~/.dsh/sessions``.

It only writes the config. It does not start Harness, install plugins, or modify profiles.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

CAPTURE_MODES = ("real-window", "desktop", "fake", "fake-blank")


def _default_lead_sessions_root() -> Path:
    dsh_home = (os.environ.get("DSH_HOME") or "").strip()
    if dsh_home:
        return Path(dsh_home).expanduser() / "sessions"
    return Path.home() / ".dsh" / "sessions"


def _posix(path: Path) -> str:
    """Forward-slash form works on Windows too and avoids YAML backslash escaping."""
    return path.as_posix()


def render_config(
    workspace: Path,
    python_exe: Path,
    lead_sessions_root: Path | None,
    capture_mode: str,
    target_window_pid: int,
) -> str:
    args: list[str] = [
        "-m",
        "ctf_solver",
        "manager",
        "serve",
        "--root",
        _posix(workspace),
        "--capture-mode",
        capture_mode,
    ]
    if target_window_pid:
        args += ["--target-window-pid", str(target_window_pid)]
    if lead_sessions_root is not None:
        args += ["--lead-sessions-root", _posix(lead_sessions_root)]

    lines = [
        "# Generated by CTF-Solver Beta: scripts/gen_mcp_config.py",
        "# Project-scoped Manager MCP entry; loaded by the Workspace MCP Bridge plugin.",
        "# This file may contain local paths. Keep it out of Git.",
        "servers:",
        "  ctf-solver:",
        "    transport: stdio",
        f'    command: "{_posix(python_exe)}"',
        "    args:",
    ]
    lines += [f'      - "{item}"' for item in args]
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate <workspace>/.dsh/mcp.servers.yml for the CTF-Solver Manager."
    )
    parser.add_argument(
        "--workspace",
        default=str(REPO_ROOT),
        help="Workspace opened in DeepSeek Harness (default: this repository).",
    )
    parser.add_argument(
        "--python",
        default=sys.executable,
        help="Interpreter that runs the Manager (default: this interpreter).",
    )
    parser.add_argument(
        "--lead-sessions-root",
        default="",
        help="Live Harness sessions root (default: $DSH_HOME/sessions or ~/.dsh/sessions).",
    )
    parser.add_argument(
        "--capture-mode",
        default="real-window",
        choices=CAPTURE_MODES,
        help="Screenshot capture mode for the Manager (default: real-window).",
    )
    parser.add_argument(
        "--target-window-pid",
        type=int,
        default=0,
        help="Explicit target window PID for real-window capture (optional here).",
    )
    parser.add_argument(
        "--out",
        default="",
        help="Output path (default: <workspace>/.dsh/mcp.servers.yml).",
    )
    parser.add_argument("--force", action="store_true", help="Overwrite an existing config.")
    parser.add_argument(
        "--dry-run", action="store_true", help="Print the config without writing a file."
    )
    args = parser.parse_args(argv)

    workspace = Path(args.workspace).expanduser().resolve()
    if not workspace.is_dir():
        print(f"error: workspace does not exist: {workspace}", file=sys.stderr)
        return 2
    python_exe = Path(args.python).expanduser().resolve()
    if not python_exe.is_file():
        print(f"error: interpreter not found: {python_exe}", file=sys.stderr)
        return 2

    if args.lead_sessions_root.strip():
        lead_root: Path | None = Path(args.lead_sessions_root).expanduser().resolve()
    else:
        lead_root = _default_lead_sessions_root()
    if lead_root is not None and not lead_root.is_dir():
        print(
            f"warning: Lead sessions root does not exist yet: {lead_root}\n"
            "         (Harness must use this root for Lead-session evidence ingestion;"
            " set --lead-sessions-root if your DSH_HOME differs.)",
            file=sys.stderr,
        )

    out = (
        Path(args.out).expanduser().resolve()
        if args.out.strip()
        else workspace / ".dsh" / "mcp.servers.yml"
    )
    if out.exists() and not args.force and not args.dry_run:
        print(
            f"error: config already exists: {out}\n"
            "       re-run with --force to overwrite (a backup is your responsibility)",
            file=sys.stderr,
        )
        return 3

    text = render_config(
        workspace=workspace,
        python_exe=python_exe,
        lead_sessions_root=lead_root,
        capture_mode=args.capture_mode,
        target_window_pid=args.target_window_pid,
    )

    if args.dry_run:
        print(text, end="")
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    print("Next: open the workspace in DeepSeek Harness with the Workspace MCP Bridge plugin")
    print("      installed, then start a conversation and confirm 18 mcp__ctf-solver__* tools.")
    if args.capture_mode == "real-window" and not args.target_window_pid:
        print(
            "note: real-window capture needs --target-window-pid before screenshots work;"
            " see KNOWN_ISSUES.md (KI-3).",
            file=sys.stderr,
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
